CREATE TABLE IF NOT EXISTS users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name TEXT NOT NULL,
 email TEXT NOT NULL UNIQUE,
 password_hash TEXT NOT NULL,
 role TEXT NOT NULL CHECK (role IN ('student', 'company')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS student_profiles (
 user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
 course TEXT, institution TEXT, skills TEXT, portfolio_url TEXT
);
CREATE TABLE IF NOT EXISTS company_profiles (
 user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
 company_name TEXT NOT NULL, industry TEXT, description TEXT
);
CREATE TABLE IF NOT EXISTS projects (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 company_id BIGINT NOT NULL REFERENCES users(id),
 title TEXT NOT NULL, description TEXT NOT NULL,
 category TEXT NOT NULL CHECK (category IN ('Marketing e design','Planilhas e dados','Desenvolvimento web simples')),
 amount_cents INTEGER NOT NULL CHECK (amount_cents >= 0),
 deadline_date DATE NOT NULL, deliverables TEXT NOT NULL,
 status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open','in_progress','delivered','completed')),
 selected_student_id BIGINT REFERENCES users(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS applications (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
 student_id BIGINT NOT NULL REFERENCES users(id),
 message TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(project_id, student_id)
);
CREATE TABLE IF NOT EXISTS deliveries (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 project_id BIGINT NOT NULL UNIQUE REFERENCES projects(id) ON DELETE CASCADE,
 student_id BIGINT NOT NULL REFERENCES users(id),
 delivery_url TEXT NOT NULL, delivered_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 approved_at TIMESTAMPTZ
);
CREATE TABLE IF NOT EXISTS reviews (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
 reviewer_id BIGINT NOT NULL REFERENCES users(id),
 reviewee_id BIGINT NOT NULL REFERENCES users(id),
 rating INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
 comment TEXT, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(project_id,reviewer_id)
);
CREATE TABLE IF NOT EXISTS simulated_payments (
 project_id BIGINT PRIMARY KEY REFERENCES projects(id) ON DELETE CASCADE,
 amount_cents INTEGER NOT NULL CHECK (amount_cents >= 0),
 commission_percent INTEGER NOT NULL DEFAULT 12 CHECK (commission_percent BETWEEN 0 AND 100),
 label TEXT NOT NULL DEFAULT 'SIMULADO — nenhuma transação real',
 displayed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_projects_status ON projects(status);
CREATE INDEX IF NOT EXISTS idx_applications_project ON applications(project_id);
