import os
import unittest
from pathlib import Path

SCHEMA = (Path(__file__).resolve().parents[1] / 'schema.sql').read_text(encoding='utf-8')
REQUIRED = {'users','student_profiles','company_profiles','projects','applications','deliveries','reviews','simulated_payments'}

class SchemaStaticTests(unittest.TestCase):
    def test_tables_exist_in_ddl(self):
        for name in REQUIRED:
            with self.subTest(name=name):
                self.assertIn(f'CREATE TABLE IF NOT EXISTS {name} ', SCHEMA)

    def test_postgres_features_and_no_sqlite_ddl(self):
        self.assertIn('GENERATED BY DEFAULT AS IDENTITY', SCHEMA)
        self.assertIn('TIMESTAMPTZ', SCHEMA)
        self.assertNotIn('AUTOINCREMENT', SCHEMA.upper())
        self.assertNotIn('PRAGMA', SCHEMA.upper())

    def test_payment_is_simulation_only(self):
        self.assertIn('SIMULADO', SCHEMA)

@unittest.skipUnless(os.environ.get('UNITASK_TEST_DATABASE_URL'), 'Configure UNITASK_TEST_DATABASE_URL para testes reais')
class PostgresIntegrationTests(unittest.TestCase):
    def setUp(self):
        import psycopg
        self.con = psycopg.connect(os.environ['UNITASK_TEST_DATABASE_URL'])
        self.con.execute('BEGIN')
        self.con.execute(SCHEMA)

    def tearDown(self):
        self.con.rollback()
        self.con.close()

    def test_required_tables_in_postgres(self):
        names = {r[0] for r in self.con.execute("SELECT tablename FROM pg_tables WHERE schemaname = current_schema()")}
        self.assertTrue(REQUIRED.issubset(names))

    def test_invalid_role_rejected(self):
        import psycopg
        with self.assertRaises(psycopg.errors.CheckViolation):
            self.con.execute("INSERT INTO users(name,email,password_hash,role) VALUES('Teste','teste@exemplo.invalid','hash','admin')")

if __name__ == '__main__':
    unittest.main()
